import re
from pathlib import Path
from django.core.management.base import BaseCommand, CommandError
from django.apps import apps
from django_star.console import console

HTML5_BOILERPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{% block title %}__TITLE__{% endblock %}</title>
    {% block extra_css %}{% endblock %}
</head>
<body>
    <header>
        <nav>
            <!-- Navigation -->
        </nav>
    </header>

    <main>
        {% block __BLOCK_NAME__ %}
        <h1>__TITLE__</h1>
        <p>Template generated by <strong>django-star</strong>.</p>
        {% endblock %}
    </main>

    <footer>
        <!-- Footer -->
    </footer>

    {% block extra_js %}{% endblock %}
</body>
</html>
"""

EXTENDS_TEMPLATE = """{% extends "__PARENT__" %}

{% block title %}__TITLE__{% endblock %}

{% block __BLOCK_NAME__ %}
<div class="__APP_LABEL__-__SLUG__">
    <h1>__TITLE__</h1>
    <p>Template content for <strong>__APP_LABEL__</strong>.</p>
</div>
{% endblock %}
"""

COMPONENT_TEMPLATE = """{% block __BLOCK_NAME__ %}
<section class="__APP_LABEL__-__SLUG__">
    <h2>__TITLE__</h2>
    <!-- Template content for __APP_LABEL__/__TEMPLATE_NAME__ -->
</section>
{% endblock %}
"""


class Command(BaseCommand):
    help = (
        "Creates a namespaced template under <app>/templates/<app>/<template>.html "
        "with options for template inheritance (--extends) and HTML5 boilerplate (--html5)."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "app_name",
            type=str,
            help="Target application label (e.g. main, website, billing)",
        )
        parser.add_argument(
            "template_name",
            type=str,
            help="Template filename or relative subpath (e.g. index, detail.html, auth/login)",
        )
        parser.add_argument(
            "-e",
            "--extends",
            type=str,
            default=None,
            help="Parent template to extend (e.g. base.html or main/base.html)",
        )
        parser.add_argument(
            "--html5",
            action="store_true",
            default=False,
            help="Generate a complete modern HTML5 document boilerplate",
        )
        parser.add_argument(
            "--flat",
            action="store_true",
            default=False,
            help="Skip the app-namespaced subdirectory and create directly under <app>/templates/",
        )
        parser.add_argument(
            "--block",
            type=str,
            default="content",
            help="Name of the primary content block (defaults to 'content')",
        )
        parser.add_argument(
            "-f",
            "--force",
            action="store_true",
            default=False,
            help="Overwrite existing template file if it already exists",
        )

    def handle(self, *args, **options):
        raw_app_name = options["app_name"]
        raw_template_name = options["template_name"]
        extends_parent = options.get("extends")
        use_html5 = options.get("html5", False)
        is_flat = options.get("flat", False)
        block_name = (options.get("block") or "content").strip()
        force = options.get("force", False)

        # 1. Resolve application in INSTALLED_APPS
        try:
            app_config = apps.get_app_config(raw_app_name)
        except LookupError:
            raise CommandError(
                f"Application '{raw_app_name}' is not in INSTALLED_APPS. "
                f"Please ensure it is added to your settings.py."
            )

        app_label = app_config.label
        app_dir = Path(app_config.path)

        # 2. Normalize template filename and relative path
        normalized_template = raw_template_name.strip().lstrip("/\\")
        # Add .html extension if none is provided
        if not re.search(r"\.[a-zA-Z0-9]+$", normalized_template):
            normalized_template += ".html"

        stem_name = Path(normalized_template).stem
        title = stem_name.replace("_", " ").replace("-", " ").title()
        slug = re.sub(r"[^a-zA-Z0-9_-]", "-", stem_name).lower()

        # 3. Determine target directory
        templates_root = app_dir / "templates"
        if is_flat:
            target_file = templates_root / normalized_template
            render_ref = normalized_template
        else:
            target_file = templates_root / app_label / normalized_template
            render_ref = f"{app_label}/{normalized_template}"

        # 4. Check for existing file
        if target_file.exists() and not force:
            console.print(
                f"[bold yellow]⚠ Template already exists:[/bold yellow] [white]{target_file}[/white]\n"
                f"[dim]Use --force (-f) to overwrite.[/dim]"
            )
            return

        # Ensure parent directories exist
        target_file.parent.mkdir(parents=True, exist_ok=True)

        # 5. Render template content
        if extends_parent:
            parent_clean = extends_parent.strip()
            if not re.search(r"\.[a-zA-Z0-9]+$", parent_clean):
                parent_clean += ".html"
            content = (
                EXTENDS_TEMPLATE.replace("__PARENT__", parent_clean)
                .replace("__TITLE__", f"{app_label.capitalize()} - {title}")
                .replace("__BLOCK_NAME__", block_name)
                .replace("__APP_LABEL__", app_label)
                .replace("__SLUG__", slug)
            )
        elif use_html5 or stem_name.lower() in ("base", "layout"):
            content = (
                HTML5_BOILERPLATE.replace("__TITLE__", f"{app_label.capitalize()} | {title}")
                .replace("__BLOCK_NAME__", block_name)
            )
        else:
            content = (
                COMPONENT_TEMPLATE.replace("__BLOCK_NAME__", block_name)
                .replace("__APP_LABEL__", app_label)
                .replace("__SLUG__", slug)
                .replace("__TITLE__", title)
                .replace("__TEMPLATE_NAME__", normalized_template)
            )

        target_file.write_text(content, encoding="utf-8")

        # 6. Console feedback
        console.print(
            f"[bold green]✔ Created template:[/bold green] [white]{target_file}[/white]\n"
            f"  [dim]Render in view:[/dim] [bold cyan]render(request, \"{render_ref}\", context)[/bold cyan]"
        )
