import re
from pathlib import Path
from django.core.management.base import BaseCommand, CommandError
from django.apps import apps
from django.conf import settings
from rich.console import Console

console = Console()

APP_URLS_TEMPLATE = """from django.urls import path
from . import views

app_name = "{app_name}"

urlpatterns = [
    # path("", views.index, name="index"),
]
"""

SAMPLE_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{{ app_name|title }}</title>
</head>
<body>
    <h1>Welcome to the {{ app_name|title }} App</h1>
    <p>Template generated by <strong>django-star</strong>.</p>
</body>
</html>
"""


class Command(BaseCommand):
    help = (
        "Creates urls.py and templates for an existing app, "
        "and binds it directly into the root urls.py"
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "app_name", type=str, help="Target application label (e.g. blog)"
        )
        parser.add_argument(
            "--prefix",
            type=str,
            default=None,
            help="URL route prefix (defaults to the app name, e.g. /blog/)",
        )
        parser.add_argument(
            "--no-template",
            action="store_true",
            help="Skip creating the templates directory and sample index.html",
        )

    def handle(self, *args, **options):
        app_label = options["app_name"].lower()
        route_prefix = options["prefix"] or app_label
        skip_template = options["no_template"]

        # 1. Verify app exists in INSTALLED_APPS
        try:
            app_config = apps.get_app_config(app_label)
        except LookupError:
            raise CommandError(
                f"Application '{app_label}' is not in INSTALLED_APPS. "
                f"Please add it to settings.py first."
            )

        app_dir = Path(app_config.path)

        # 2. Generate <app>/urls.py if missing
        app_urls_file = app_dir / "urls.py"
        if not app_urls_file.exists():
            app_urls_file.write_text(
                APP_URLS_TEMPLATE.format(app_name=app_label), encoding="utf-8"
            )
            console.print(
                f"[bold green]✔ Created[/bold green] [white]{app_urls_file}[/white]"
            )
        else:
            console.print(
                f"[bold yellow]⚠ {app_urls_file.name} already exists. Skipping creation.[/bold yellow]"
            )

        # 3. Generate templates/<app>/index.html
        if not skip_template:
            template_dir = app_dir / "templates" / app_label
            template_dir.mkdir(parents=True, exist_ok=True)
            index_html = template_dir / "index.html"
            if not index_html.exists():
                index_html.write_text(
                    SAMPLE_TEMPLATE.replace(
                        "{{ app_name|title }}", app_label.capitalize()
                    ),
                    encoding="utf-8",
                )
                console.print(
                    f"[bold green]✔ Created template[/bold green] [white]{index_html}[/white]"
                )
            else:
                console.print(
                    f"[bold yellow]⚠ Template {index_html.name} already exists. Skipping.[/bold yellow]"
                )

        # 4. Wire route inside Root urls.py
        self._wire_root_urls(app_label, route_prefix.strip("/"))

    def _wire_root_urls(self, app_name: str, route_prefix: str):
        root_urlconf = getattr(settings, "ROOT_URLCONF", None)
        if not root_urlconf:
            console.print("[bold red]✖ ROOT_URLCONF not found in settings.[/bold red]")
            return

        base_dir = Path(settings.BASE_DIR)
        root_urls_path = base_dir / (root_urlconf.replace(".", "/") + ".py")
        if not root_urls_path.exists():
            console.print(
                f"[bold red]✖ Root url file not found at {root_urls_path}[/bold red]"
            )
            return

        content = root_urls_path.read_text(encoding="utf-8")

        # Check if already included
        route_signature = f'"{app_name}.urls"'
        alt_signature = f"'{app_name}.urls'"
        if route_signature in content or alt_signature in content:
            console.print(
                f"[bold yellow]⚠ '{app_name}.urls' is already mounted in {root_urls_path.name}.[/bold yellow]"
            )
            return

        # 1. Ensure 'include' is imported from django.urls
        if "include" not in content:
            content = re.sub(
                r"from django\.urls import ([\w\s,]+)",
                r"from django.urls import \1, include",
                content,
                count=1,
            )

        # 2. Append route to urlpatterns
        new_route = f'    path("{route_prefix}/", include("{app_name}.urls")),\n'
        pattern = r"(urlpatterns\s*=\s*\[)([\s\S]*?)(\])"
        match = re.search(pattern, content)

        if match:
            head, body, tail = match.group(1), match.group(2), match.group(3)
            new_urlpatterns = f"{head}{body}{new_route}{tail}"
            content = (
                content[: match.start()] + new_urlpatterns + content[match.end() :]
            )
            root_urls_path.write_text(content, encoding="utf-8")
            console.print(
                f"[bold green]✔ Mounted[/bold green] [cyan]/{route_prefix}/[/cyan] "
                f"$\to$ [white]{root_urls_path.name}[/white]"
            )
        else:
            console.print(
                "[bold yellow]⚠ Could not find 'urlpatterns = [...]' block in root urls.py[/bold yellow]"
            )
